"""Generate four LaTeX floats from release data (requires NumPy)."""
import csv
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "results"
OUT = ROOT / "paper" / "tables"


def load(name):
    return json.loads((DATA / (name + ".json")).read_bytes())


def table(name, caption, headers, alignment, rows):
    lines = ["% Generated by scripts/make_paper_tables.py", r"\begin{table*}[tb]",
             r"\centering\small", r"\caption{" + caption + "}", r"\label{tab:" + name + "}",
             r"\begin{tabular}{@{}" + alignment + "@{}}", r"\toprule", headers + r" \\", r"\midrule"]
    lines.extend(" & ".join(map(str, row)) + r" \\" for row in rows)
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table*}"])
    (OUT / (name + ".tex")).write_bytes(("\n".join(lines) + "\n").encode())


def pairs(records):
    values = {(r["layout"], r["noise"]): int(r["success"]) for r in records}
    if len(values) != len(records):
        raise ValueError("Duplicate layout and noise seed")
    return values


def closed_loop():
    frozen = load("plus-light-contrast")["comparison"]
    adjusted_lo, adjusted_hi = frozen["familywise95_pp"]
    rows = []
    for label, source, control, shared in [
        ("Object, single", "object", "B-BC", "B-Bo4"),
        ("Object, original Bo4", "object", "B-OrigBo4", "B-Bo4"),
        ("Long Task2, single", "long-task2", "Z", "SharedBo4"),
        ("Plus lighting, single", "plus-light", "Plus_light_BC", "Plus_light_Bo4"),
    ]:
        arms = load(source + "-paired")
        a, b = pairs(arms[control]), pairs(arms[shared])
        if a.keys() != b.keys():
            raise ValueError(f"Unmatched episodes in {source}")
        layouts = defaultdict(list)
        for key in sorted(a):
            layouts[key[0]].append(b[key] - a[key])
        if len({len(group) for group in layouts.values()}) != 1:
            raise ValueError("Expected equal repeat counts across layouts")
        values = np.array([np.mean(group) for group in layouts.values()])
        if source == "plus-light":
            if not np.isclose(values.mean() * 100, frozen["delta_pp"]):
                raise ValueError("Frozen Plus-light contrast disagrees with paired outcomes")
            lo, hi = frozen["ci95_pp"]
        else:
            means = np.random.default_rng(42).choice(values, (20000, len(values))).mean(axis=1)
            lo, hi = np.percentile(100 * means, [2.5, 97.5])
        rows.append([label, len(a), sum(a.values()), sum(b.values()),
                     "$" + f"{values.mean()*100:+.2f}$", f"$[{lo:.2f}, {hi:.2f}]$"])
    table("closed-loop", r"Success counts and shared Bo4 minus control differences in percentage points. "
          r"Object and Long paired 95\% percentile intervals resample physical layouts 20,000 times (seed 42), keeping "
          r"noise repeats together. For Plus lighting both intervals come from the archived protocol confirmation. "
          f"The familywise interval is $[{adjusted_lo:.2f}, {adjusted_hi:.2f}]$ pp.",
          r"Suite and control & Episodes & Control & Shared Bo4 & $\Delta$ (pp) & 95\% CI (pp)", "lrrrrr", rows)


def scaling():
    fields = ("median_ms", "p90_ms", "peak_allocated_mib", "peak_reserved_mib")
    with (DATA / "fixed-observation-latency.csv").open(newline="") as stream:
        rows = [[r["N"], r["implementation"], *[f"{float(r[k]):.2f}" for k in fields]]
                for r in csv.DictReader(stream)]
    table("scaling", r"A100 fixed-observation decision latency and peak GPU memory over "
          r"60 repetitions per condition. Both implementations score candidates at $N=1$. "
          r"Memory is in MiB ($2^{20}$ bytes).",
          "$N$ & Implementation & Median (ms) & P90 (ms) & Allocated (MiB) & Reserved (MiB)", "rlrrrr", rows)


def profile():
    rows = []
    for record in load("profile")["rows"]:
        for stage in ("vision", "prefix", "expert", "critic"):
            s = record["stages"][stage]
            rows.append([record["n"], stage, f"{s['ms']:.2f}", f"{s['flops']/1e9:.1f}",
                         *[f"{s['bytes'][k]/1e9:.3f}" for k in
                           ("weight_read", "activation_read", "activation_write")]])
    table("profile", r"Shared decision stages on A100. Times are medians of 20 measurements. "
          r"Registered operator FLOPs and logical tensor traffic use decimal giga-units "
          r"($10^9$). Physical DRAM traffic was unmeasured.",
          "$N$ & Stage & ms & GFLOP & Weight read (GB) & Act. read (GB) & Act. write (GB)", "rlrrrrr", rows)


def precision():
    summary = load("precision/summary")
    scores = load("precision/scores")
    cases = load("precision/closed_loop")["cases"].values()
    rows = []
    for label, key, arm in [("Original", "original", "B-Bo4"), ("INT8", "int8", "int8"),
                            ("FP16", "float16", None), ("BF16", "bfloat16", None)]:
        size = summary["original_bytes"] if key == "original" else summary["formats"][key]["bytes"]
        hits = sum(np.argmax(r[key]) == np.argmax(r["original"]) for r in scores)
        outcome = f"{sum(r[arm] for r in cases)}/{len(cases)}" if arm else "--"
        rows.append([label, f"{size:,}", f"{size/1e6:.2f}", f"{hits}/{len(scores)}", outcome])
    single = sum(r["B-BC"] for r in cases)
    table("precision", f"Persistent critic payload (including scales), replay winner agreement "
          f"with the original critic, and paired Object successes. The single-proposal control "
          f"succeeded on {single}/{len(cases)} episodes. Dashes indicate unevaluated arms. "
          r"INT8 weights are unpacked for computation. MB denotes $10^6$ bytes.",
          "Storage & Bytes & MB & Winner agreement & Successes", "lrrrr", rows)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    closed_loop()
    scaling()
    profile()
    precision()
