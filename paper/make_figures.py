"""Generate paper figures, headline macros and the CUDA Graph table from results."""
import argparse
from pathlib import Path
from statistics import mean, median
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from make_paper_tables import ROOT, load, table

PAPER = ROOT / "paper"
FIGURES = PAPER / "figures"
COLORS = ("#b7c9d8", "#7896ae", "#234d73", "#8c6647")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--numbers-only", action="store_true", help="Regenerate TeX evidence without rendering plots")
    args = parser.parse_args()
    FIGURES.mkdir(parents=True, exist_ok=True)
    obj = load("object-paired")
    long = load("long-task2-paired")
    precision = load("precision/summary")

    def effect(arms, base, method):
        return 100 * (mean(r["success"] for r in arms[method]) -
                      mean(r["success"] for r in arms[base]))

    bc, original, shared = [
        1000 * mean(t for row in obj[arm] for t in row["decision_seconds"])
        for arm in ("B-BC", "B-OrigBo4", "B-Bo4")
    ]
    graph_data = load("cuda-graph")
    rows = graph_data["p5_precision"]
    ns = [r["n"] for r in rows]
    columns = [(path, stage) for stage in ("expert_ms", "full_ms") for path in ("eager", "graph")]
    graph_times = [[median(s[stage] for s in r["samples"][path]) for path, stage in columns]
                   for r in rows]
    base_expert, graph_expert, base_full, graph_full = graph_times[ns.index(4)]
    values = {
        "ObjectEpisodes": str(len(obj["B-BC"])),
        "SingleWins": str(sum(r["success"] for r in obj["B-BC"])),
        "SharedWins": str(sum(r["success"] for r in obj["B-Bo4"])),
        "OriginalWins": str(sum(r["success"] for r in obj["B-OrigBo4"])),
        "SharingReduction": f"{100*(1-shared/original):.1f}",
        "ObjectGain": f"{effect(obj, 'B-BC', 'B-Bo4'):.2f}",
        "LongGain": f"{effect(long, 'Z', 'SharedBo4'):.2f}",
        "BaselineTime": f"{bc:.2f}", "OriginalTime": f"{original:.2f}", "SharedTime": f"{shared:.2f}",
        "OriginalOverhead": f"{100*(original/bc-1):.1f}", "SharedOverhead": f"{100*(shared/bc-1):.1f}",
        "FullPrecisionMB": f"{precision['original_bytes']/1e6:.2f}",
        "PackedMB": f"{precision['formats']['int8']['bytes']/1e6:.2f}",
        "ExpertEager": f"{base_expert:.2f}", "ExpertGraph": f"{graph_expert:.2f}",
        "DecisionEager": f"{base_full:.2f}", "DecisionGraph": f"{graph_full:.2f}",
        "ExpertReduction": f"{100*(1-graph_expert/base_expert):.1f}",
        "FpChecks": str(sum(len(r["parity"]) for r in graph_data["fp32"])),
    }
    (PAPER / "metrics.tex").write_text(
        "% Generated by paper/make_figures.py\n" +
        "".join(chr(92) + "newcommand{" + chr(92) + key + "}{" + value + "}" + chr(10)
                for key, value in values.items()),
        encoding="ascii",
    )
    table("graph", "Matched eager and warm CUDA Graph replay on a fixed Object observation. "
          "Reported medians include refreshing graph inputs and exclude one-time capture.",
          "$N$ & Expert eager (ms) & Expert graph (ms) & Decision eager (ms) & Decision graph (ms)",
          "rrrrr", [[n, *[f"{t:.2f}" for t in times]] for n, times in zip(ns, graph_times)])

    if args.numbers_only:
        return
    import matplotlib.pyplot as plt

    plt.rcParams.update({"font.size": 8, "axes.labelsize": 8, "legend.fontsize": 7.5,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "axes.linewidth": .65, "pdf.fonttype": 42})
    fig, ax = plt.subplots(figsize=(3.42, 2.14), constrained_layout=True)
    for index, label, marker, color, style in (
        (2, "Matched eager", "o", "#545b65", "--"),
        (3, "Warm CUDA Graph", "s", COLORS[2], "-"),
    ):
        ax.plot(ns, [t[index] for t in graph_times], marker=marker, color=color,
                linestyle=style, linewidth=1.2, markersize=4, label=label)
    ax.set(xlabel="Number of candidates", ylabel="Median decision time (ms)", xticks=ns)
    ax.set_axisbelow(True)
    ax.grid(axis="y", color="#d8dce0", linewidth=.5)
    ax.legend(frameon=False, loc="center right")
    fig.savefig(FIGURES / "decision-latency.pdf", metadata={"CreationDate": None})
    plt.close(fig)

    profile = [r for r in load("profile")["rows"] if r["n"] in ns]
    fig, ax = plt.subplots(figsize=(3.42, 2.14), constrained_layout=True)
    base = [0.] * len(profile)
    for stage, label, color in zip(("vision", "prefix", "expert", "critic"),
                                   ("Vision", "Prefix", "Action expert", "Critic"), COLORS):
        height = [r["stages"][stage]["ms"] for r in profile]
        ax.bar(range(len(profile)), height, bottom=base, width=.57, label=label, color=color)
        base = [x + y for x, y in zip(base, height)]
    ax.set(xlabel="Number of candidates", ylabel="Sum of stage medians (ms)",
           xticks=range(len(profile)), xticklabels=[r["n"] for r in profile], ylim=(0, 310))
    ax.set_axisbelow(True)
    ax.grid(axis="y", color="#d8dce0", linewidth=.5)
    ax.legend(frameon=False, ncol=2, loc="upper center")
    fig.savefig(FIGURES / "stage-latency.pdf", metadata={"CreationDate": None})
    plt.close(fig)


if __name__ == "__main__":
    main()
